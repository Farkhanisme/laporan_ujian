-- Seed nilai ASTS (Asesmen Sumatif Tengah Semester)
-- MTsS MA'ARIF TIENG | Tahun ajaran 2026/2027 | Semester GANJIL
-- Tabel: siswa, mapel, nilai   (SQLite / Turso libSQL)
-- Pakai:  turso db shell <nama-db> < seed_asts_turso.sql
--
-- Catatan:
--  * nilai_asli    : nilai dari file Excel (bilangan bulat), tidak boleh diubah oleh proses dongkrak.
--  * nilai_dongkrak: kosong (NULL) = belum didongkrak. Diisi oleh aplikasi.
--  * Mapel yang tidak ada nilainya di file Excel diisi nilai_asli = 0.
--  * Nilai desimal di file Excel (mapel IPS, 124 nilai) sudah dibulatkan ke bilangan bulat terdekat.

DROP TABLE IF EXISTS nilai;
DROP TABLE IF EXISTS mapel;
DROP TABLE IF EXISTS siswa;

CREATE TABLE siswa (
  id        INTEGER PRIMARY KEY AUTOINCREMENT,
  nis       TEXT UNIQUE,                -- diisi nanti (TEXT agar angka 0 di depan tidak hilang)
  nisn      TEXT UNIQUE,                -- diisi nanti
  nama      TEXT NOT NULL,
  kelas     TEXT NOT NULL,              -- 7A, 7B, 8A, 8B, 9
  UNIQUE (nama, kelas)
);

CREATE TABLE mapel (
  id        INTEGER PRIMARY KEY AUTOINCREMENT,
  nama      TEXT NOT NULL,
  tingkat   INTEGER NOT NULL,           -- 7, 8, 9
  kode      TEXT NOT NULL,              -- kode mapel di aplikasi ujian
  UNIQUE (nama, tingkat)
);

CREATE TABLE nilai (
  id              INTEGER PRIMARY KEY AUTOINCREMENT,
  siswa_id        INTEGER NOT NULL REFERENCES siswa(id) ON DELETE CASCADE,
  mapel_id        INTEGER NOT NULL REFERENCES mapel(id) ON DELETE CASCADE,
  nilai_asli      INTEGER NOT NULL CHECK (nilai_asli BETWEEN 0 AND 100),
  nilai_dongkrak  INTEGER CHECK (nilai_dongkrak IS NULL OR nilai_dongkrak BETWEEN 0 AND 100),
  UNIQUE (siswa_id, mapel_id)
);

CREATE INDEX idx_nilai_mapel ON nilai(mapel_id);

